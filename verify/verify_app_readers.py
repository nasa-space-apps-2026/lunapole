#!/usr/bin/env python3
"""Cross-check the browser's binary readers against the Python bakers.

Run:  python verify/verify_app_readers.py

The app parses `LUNAHOR` and `LUNATRN` by hand in `app/src/artifacts.js`. A
one-field offset error would still render a convincing picture, so this script
runs the actual JS module under Node (with a `fetch` shim that reads the same
files) and compares every parsed value against the Python reader:

  * horizon header fields, bin count, per-bin elevation / distance / flags
  * `horizonAt()` vs `build.lunapole.horizon.horizon_at()` at 41 azimuths
  * terrain header fields, sample count, and the exact int16 height array
  * the per-site series JSON parses to the same row lengths

Exit codes: 0 pass, 1 mismatch, 2 BLOCKED (no node, no artifacts).
"""
from __future__ import annotations

import json
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import _bootstrap  # noqa: E402

_bootstrap.utf8_streams()

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from build.lunapole import horizon as horizon_mod  # noqa: E402

HORIZON_DIR = ROOT / "artifacts" / "horizon"
TERRAIN_DIR = ROOT / "app" / "data" / "terrain"
SERIES_GLOB = "*_*d.json"

HARNESS = r"""
// Generated by verify/verify_app_readers.py - do not ship.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = process.argv[2];
globalThis.fetch = async (url) => {
  const file = path.join(root, String(url).replace(/^\.?\//, ""));
  const buf = fs.readFileSync(file);
  return {
    ok: true,
    status: 200,
    arrayBuffer: async () => buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength),
  };
};

const mod = await import(pathToFileURL(path.join(root, "app/src/artifacts.js")).href);
const out = { horizons: {}, terrains: {}, series: {} };

for (const name of fs.readdirSync(path.join(root, "artifacts/horizon"))) {
  if (!name.endsWith(".bin")) continue;
  const h = await mod.loadHorizon(`artifacts/horizon/${name}`);
  out.horizons[h.siteId] = {
    bins: h.bins, stepM: h.stepM, maxDistKm: h.maxDistKm,
    lat: h.lat, lon: h.lon, siteHM: h.siteHM,
    elevDeg: Array.from(h.elevDeg),
    shadowDistKm: Array.from(h.shadowDistKm),
    obstacleHM: Array.from(h.obstacleHM).map((v) => (Number.isNaN(v) ? null : v)),
    flags: Array.from(h.flags), provenance: Array.from(h.provenance),
    farFieldBins: h.farFieldBins, gaps: h.gaps,
    horizonAt: Array.from({ length: 41 }, (_, k) => mod.horizonAt(h, k * 9)),
  };
}

for (const name of fs.readdirSync(path.join(root, "app/data/terrain"))) {
  if (!name.endsWith(".bin")) continue;
  const t = await mod.loadTerrain(`app/data/terrain/${name}`);
  out.terrains[t.siteId] = {
    n: t.n, gridM: t.gridM, cxM: t.cxM, cyM: t.cyM,
    minM: t.minM, maxM: t.maxM, sideM: t.sideM,
    z: Array.from(t.z),
  };
}

const seriesDir = path.join(root, "artifacts/maps/timeseries");
if (fs.existsSync(seriesDir)) {
  for (const name of fs.readdirSync(seriesDir)) {
    if (!name.endsWith(".json")) continue;
    const s = await mod.loadSeries(`artifacts/maps/timeseries/${name}`);
    out.series[name] = {
      samples: s.rows.et_tdb.length,
      stepMin: s.meta.step_min,
      spanDays: s.meta.span_days,
      spanLabel: s.meta.span_label,
      keys: Object.keys(s.rows).sort(),
    };
  }
}

process.stdout.write(JSON.stringify(out));
"""


def read_terrain(path: Path) -> dict:
    data = path.read_bytes()
    magic, ver, sid_b, n, grid_m, cx, cy = struct.unpack_from("<8sH16sIddd", data, 0)
    if magic != b"LUNATRN\0":
        raise ValueError(f"{path}: bad magic {magic!r}")
    z = np.frombuffer(data, dtype="<i2", offset=54, count=n * n)
    return {
        "site_id": sid_b.split(b"\0")[0].decode(),
        "n": n, "grid_m": grid_m, "cx_m": cx, "cy_m": cy,
        "min_m": int(z.min()), "max_m": int(z.max()),
        "z": z,
    }


def stage_tree(stage: Path, tmp: Path) -> Path:
    """Mirror an in-flight bake stage into the layout the app expects.

    A running bake writes `artifacts/.stage-<pid>/{ephemeris,horizon,maps}` and
    promotes only at the end. Copying the few small files into a temp root lets
    the JS readers be checked *before* promotion, without touching the product
    directories that `bake.py --verify` inspects.
    """
    root = tmp / "root"
    (root / "app" / "src").mkdir(parents=True)
    shutil.copy2(ROOT / "app" / "src" / "artifacts.js",
                 root / "app" / "src" / "artifacts.js")
    for sub, dst in (("horizon", "artifacts/horizon"),
                     ("maps", "artifacts/maps")):
        src = stage / sub
        if not src.is_dir():
            continue
        for item in src.rglob("*"):
            if item.is_file():
                out = root / dst / item.relative_to(src)
                out.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(item, out)
    for item in (ROOT / "app" / "data" / "terrain").glob("*.bin"):
        out = root / "app" / "data" / "terrain" / item.name
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, out)
    return root


def main() -> int:
    args = [a for a in sys.argv[1:]]
    stage = None
    if len(args) == 2 and args[0] == "--from-stage":
        stage = Path(args[1]).resolve()

    node = shutil.which("node")
    if node is None:
        print("BLOCKED: node not on PATH; the JS readers cannot be exercised")
        return 2
    horizon_dir = (stage / "horizon") if stage else HORIZON_DIR
    if not horizon_dir.is_dir() or not any(horizon_dir.glob("*.bin")):
        print("BLOCKED: artifacts/horizon/*.bin missing - bake first")
        return 2
    if not TERRAIN_DIR.is_dir() or not any(TERRAIN_DIR.glob("*.bin")):
        print("BLOCKED: app/data/terrain/*.bin missing - run scripts/export_terrain.py")
        return 2
    series_dir = ((stage / "maps" / "timeseries") if stage
                  else ROOT / "artifacts" / "maps" / "timeseries")

    with tempfile.TemporaryDirectory(prefix="lunapole-readers-") as tmp:
        tmp_path = Path(tmp)
        root = stage_tree(stage, tmp_path) if stage else ROOT
        harness = tmp_path / "harness.mjs"
        harness.write_text(HARNESS, encoding="utf-8")
        proc = subprocess.run([node, str(harness), str(root)],
                              capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        print("FAIL: node harness failed")
        print(proc.stderr.strip()[-3000:])
        return 1
    js = json.loads(proc.stdout)

    failures: list[str] = []

    def eq(label: str, got, want, tol=0.0):
        if isinstance(want, float) or isinstance(got, float):
            good = abs(float(got) - float(want)) <= tol
        else:
            good = got == want
        if not good:
            failures.append(f"{label}: js={got!r} py={want!r}")
        return good

    horizons = sorted(horizon_dir.glob("*.bin"))
    print("=== horizon readers ===")
    worst_interp = 0.0
    for path in horizons:
        py = horizon_mod.read_horizon(path)
        sid = path.stem
        if sid not in js["horizons"]:
            failures.append(f"{sid}: JS did not load the horizon")
            continue
        j = js["horizons"][sid]
        ok = True
        ok &= eq(f"{sid}.bins", j["bins"], len(py["elev_deg"]))
        ok &= eq(f"{sid}.lat", j["lat"], float(py["site_lat"]), 1e-5)
        ok &= eq(f"{sid}.lon", j["lon"], float(py["site_lon"]), 1e-5)
        ok &= eq(f"{sid}.siteHM", j["siteHM"], float(py["site_h_m"]), 1e-3)
        ok &= eq(f"{sid}.maxDistKm", j["maxDistKm"], float(py["max_dist_km"]), 1e-5)
        ok &= eq(f"{sid}.stepM", j["stepM"], float(py["step_m"]), 1e-3)
        je = np.asarray(j["elevDeg"], dtype=np.float64)
        pe = np.asarray(py["elev_deg"], dtype=np.float64)
        ok &= eq(f"{sid}.elevDeg", float(np.max(np.abs(je - pe))), 0.0, 1e-6)
        pd = np.asarray(py["shadow_dist_km"], dtype=np.float64)
        jd = np.asarray(j["shadowDistKm"], dtype=np.float64)
        ok &= eq(f"{sid}.shadowDistKm", float(np.max(np.abs(jd - pd))), 0.0, 1e-5)
        ok &= eq(f"{sid}.flags", list(map(int, py["flags"])), j["flags"])
        ok &= eq(f"{sid}.provenance", list(map(int, py["provenance"])), j["provenance"])
        ok &= eq(f"{sid}.farFieldBins", sum(int(f) & 1 for f in py["flags"]),
                 j["farFieldBins"])
        ok &= eq(f"{sid}.gaps", sum(int(p) == 2 for p in py["provenance"]), j["gaps"])

        py_at = horizon_mod.horizon_at(py, np.arange(41) * 9.0)
        delta = float(np.max(np.abs(np.asarray(j["horizonAt"]) - py_at)))
        worst_interp = max(worst_interp, delta)
        ok &= eq(f"{sid}.horizonAt", delta, 0.0, 1e-5)
        print(f"  [{'PASS' if ok else 'FAIL'}] {sid:<12} {j['bins']} bins  "
              f"elev {je.min():+.2f}..{je.max():+.2f} deg  "
              f"far-field {j['farFieldBins']}/{j['bins']}  "
              f"interp worst {delta:.2e} deg")

    print("\n=== terrain readers ===")
    for path in sorted(TERRAIN_DIR.glob("*.bin")):
        sid = path.stem
        py = read_terrain(path)
        if sid not in js["terrains"]:
            failures.append(f"{sid}: JS did not load the terrain")
            continue
        j = js["terrains"][sid]
        ok = True
        ok &= eq(f"{sid}.n", j["n"], py["n"])
        ok &= eq(f"{sid}.grid_m", j["gridM"], py["grid_m"], 1e-9)
        ok &= eq(f"{sid}.cx_m", j["cxM"], py["cx_m"], 1e-6)
        ok &= eq(f"{sid}.cy_m", j["cyM"], py["cy_m"], 1e-6)
        ok &= eq(f"{sid}.min_m", j["minM"], py["min_m"])
        ok &= eq(f"{sid}.max_m", j["maxM"], py["max_m"])
        jz = np.asarray(j["z"], dtype=np.int16)
        ok &= eq(f"{sid}.z", int(np.count_nonzero(jz != py["z"])), 0)
        print(f"  [{'PASS' if ok else 'FAIL'}] {sid:<12} {j['n']}x{j['n']}  "
              f"{j['gridM']:.2f} m  z {j['minM']}..{j['maxM']} m  "
              f"exact int16 match")

    print("\n=== series readers ===")
    for path in sorted(series_dir.glob(SERIES_GLOB)) if series_dir.is_dir() else []:
        payload = json.loads(path.read_text(encoding="utf-8"))
        name = path.name
        if name not in js["series"]:
            failures.append(f"{name}: JS did not load the series")
            continue
        j = js["series"][name]
        ok = True
        ok &= eq(f"{name}.samples", j["samples"], len(payload["rows"]["et_tdb"]))
        ok &= eq(f"{name}.step_min", j["stepMin"], payload["meta"]["step_min"])
        ok &= eq(f"{name}.span_days", j["spanDays"], payload["meta"]["span_days"])
        ok &= eq(f"{name}.span_label", j["spanLabel"], payload["meta"]["span_label"])
        ok &= eq(f"{name}.row_keys", j["keys"], sorted(payload["rows"].keys()))
        print(f"  [{'PASS' if ok else 'FAIL'}] {name:<28} {j['samples']} samples  "
              f"{j['stepMin']} min  {j['spanDays']} d  label reproduced")

    print()
    if failures:
        print(f"{len(failures)} mismatch(es):")
        for line in failures[:40]:
            print("  -", line)
        return 1
    print(f"PASS: JS and Python readers agree on {len(horizons)} horizon(s), "
          f"{len(js['terrains'])} terrain(s), {len(js['series'])} series; "
          f"worst horizon interpolation delta {worst_interp:.1e} deg")
    return 0


if __name__ == "__main__":
    sys.exit(main())
